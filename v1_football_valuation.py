def make_plots(df, feature_cols):
    sns.set_style('whitegrid')

    # Plot 1: Correlation Heatmap (değişmedi)
    num_cols = feature_cols + ['market_value_in_eur', 'predicted_value', 'value_gap']
    plt.figure(figsize=(10, 8))
    sns.heatmap(df[num_cols].corr(), annot=True, fmt='.2f',
                cmap='coolwarm', center=0, square=True)
    plt.title('Feature Correlation Heatmap', fontsize=14, weight='bold')
    plt.tight_layout()
    plt.savefig(os.path.join(OUTPUT_DIR, 'correlation_heatmap.png'), dpi=150)
    plt.show()

    # Plot 2: Outlier'ları clip'le → %2 ile %98 arası göster
    q_low  = df['value_gap'].quantile(0.02)
    q_high = df['value_gap'].quantile(0.98)
    df_plot = df[(df['value_gap'] >= q_low) & (df['value_gap'] <= q_high)].copy()

    plt.figure(figsize=(11, 6))
    sns.histplot(data=df_plot, x='value_gap', hue='player_archetype',
                 kde=True, element='step', stat='density', common_norm=False)
    plt.axvline(0, color='black', linestyle='--', lw=1.5, label='Fair Value')
    plt.title('Value Gap Distribution by Archetype\n(Outliers clipped: %2–%98)',
              fontsize=14, weight='bold')
    plt.xlabel('Value Gap (Predicted − Market) EUR')
    plt.legend()
    plt.tight_layout()
    plt.savefig(os.path.join(OUTPUT_DIR, 'value_gap_distribution.png'), dpi=150)
    plt.show()
    print('✓ Plots saved to', OUTPUT_DIR)

