def build_recommendations(df):
    print('[STEP 4] Building recommendations...')

    df['value_gap'] = df['predicted_value'] - df['market_value_in_eur']

    # Her cluster içinde kendi top %25'i → 'Recommended'
    threshold = df.groupby('cluster_id')['value_gap'].transform(lambda s: s.quantile(0.75))
    df['recommendation'] = np.where(df['value_gap'] >= threshold, 'Recommended', 'Hold')

    name_col = 'name_player' if 'name_player' in df.columns else 'name'
    df['player_name'] = df[name_col]

    rec = (df[['player_name', 'age_at_valuation', 'player_archetype',
               'market_value_in_eur', 'predicted_value', 'value_gap', 'recommendation']]
           .sort_values('value_gap', ascending=False)
           .reset_index(drop=True))

    top30 = rec.head(30)
    print(top30.to_string(index=False))

    out_path = os.path.join(OUTPUT_DIR, 'undervalued_players.json')
    with open(out_path, 'w') as f:
        json.dump(top30.to_dict(orient='records'), f, indent=2, default=str)
    print(f'\n✓ Saved → {out_path}')
    return rec

