def engineer_features(df):
    print('[STEP 2] Engineering features...')

    # Per-90 stats (0 dakika → NaN yaparak sıfıra bölmeyi engelle)
    mins = df['total_minutes_played'].replace(0, np.nan)
    df['goals_per_90']   = (df['total_goals']   / mins) * 90
    df['assists_per_90'] = (df['total_assists'] / mins) * 90

    # Valuation anındaki yaş
    df['date_of_birth']  = pd.to_datetime(df['date_of_birth'],  errors='coerce')
    df['valuation_date'] = pd.to_datetime(df['valuation_date'], errors='coerce')
    df['age_at_valuation'] = (df['valuation_date'] - df['date_of_birth']).dt.days / 365.25
    # valuation_date yoksa doğum yılından hesapla
    df['age_at_valuation'] = df['age_at_valuation'].fillna(
        2024 - pd.to_datetime(df['date_of_birth'], errors='coerce').dt.year
    )

    # Lig tier: kulüp toplam değerine göre 3'e böl (Tier1=en zengin %33)
    club_val_col = 'total_market_value' if 'total_market_value' in df.columns else 'total_market_value_in_eur'
    club_value   = pd.to_numeric(df[club_val_col], errors='coerce')

    # Handle case where club_value might be all NaNs
    if club_value.isnull().all():
        print(f"  Warning: '{club_val_col}' column is all NaN or non-numeric. 'league_tier' will be all NaN.")
        df['league_tier'] = np.nan
    else:
        p33, p66     = club_value.quantile([0.33, 0.66])
        df['league_tier'] = club_value.apply(
            lambda v: np.nan if pd.isna(v) else (1 if v >= p66 else (2 if v >= p33 else 3))
        )

    feature_cols = [
        'goals_per_90', 'assists_per_90', 'age_at_valuation', 'league_tier',
        'total_minutes_played', 'total_goals', 'total_assists'
    ]

    # Remove 'league_tier' from feature_cols if it's all NaNs
    if df['league_tier'].isnull().all():
        print("  Warning: 'league_tier' is entirely NaN and will be removed from imputation and clustering.")
        feature_cols.remove('league_tier')
        cluster_cols = ['goals_per_90', 'assists_per_90', 'age_at_valuation'] # Removed league_tier
    else:
        cluster_cols     = ['goals_per_90', 'assists_per_90', 'age_at_valuation', 'league_tier']

    # Median imputation (outlier'lara karşı dayanıklı)
    imputer = SimpleImputer(strategy='median')
    df[feature_cols] = imputer.fit_transform(df[feature_cols])

    # KMeans için scale et (RF/XGBoost için gerek yok)
    X_cluster_scaled = StandardScaler().fit_transform(df[cluster_cols])

    print(f'  {len(feature_cols)} features ready | {len(df)} players')
    return df, X_cluster_scaled, feature_cols

df, X_cluster_scaled, feature_cols = engineer_features(df)

def train_models(df, feature_cols, X_cluster_scaled):
    print("[STEP 3] Computing formula-based predicted values...")

    # BASE: düşük değerli oyuncuları filtrele (en az 500K€)
    # böylece median amatör oyunculardan etkilenmiyor
    active = df[df['market_value_in_eur'] >= 500_000]
    base = active['market_value_in_eur'].median()
    print(f"  Base (median of players ≥500K€): €{base:,.0f}")

    # AGE FACTOR: zirve 26, daha geniş pencere (sigma büyütüldü)
    # eski: exp(-0.04 * (age-25.5)²) → çok dar, yaşlıları mahvediyordu
    # yeni: exp(-0.02 * (age-26)²)  → daha affedici
    age = df['age_at_valuation'].clip(15, 45)
    age_factor = np.exp(-0.02 * (age - 26) ** 2)

    # PERFORMANCE FACTOR: career total'ı normalize et
    # per_90 zaten var ama ham toplamı da ekleyelim (Messi/Ronaldo için)
    goals_norm   = df['goals_per_90'].clip(0, 5)
    assists_norm = df['assists_per_90'].clip(0, 3)
    # kariyer toplamını da hafifçe dahil et (log ile bastır)
    career_bonus = np.log1p(df['total_goals'] + df['total_assists']) / 10
    perf_factor  = 1 + 2.5 * goals_norm + 1.5 * assists_norm + career_bonus

    # TIER FACTOR
    tier_map    = {1: 4.0, 2: 1.8, 3: 0.6}
    tier_factor = df['league_tier'].map(tier_map).fillna(1.0)

    # PREDICTED VALUE
    df['predicted_value'] = base * age_factor * perf_factor * tier_factor

    print(f"  Predicted value range: "
          f"€{df['predicted_value'].min():,.0f} – €{df['predicted_value'].max():,.0f}")

    # KMeans (değişmedi)
    km = KMeans(n_clusters=4, random_state=RANDOM_STATE, n_init=10)
    df['cluster_id'] = km.fit_predict(X_cluster_scaled)

    c        = km.cluster_centers_
    ids      = list(range(4))
    elite    = max(ids,                           key=lambda i: c[i, 0])
    ids2     = [i for i in ids  if i != elite]
    play     = max(ids2,                          key=lambda i: c[i, 1])
    ids3     = [i for i in ids2 if i != play]
    prospect = min(ids3,                          key=lambda i: c[i, 2])
    work     = [i for i in ids3 if i != prospect][0]

    label_map = {elite: 'Elite Scorer', play: 'Playmaker',
                 prospect: 'Prospect',  work: 'Workhorse'}
    df['player_archetype'] = df['cluster_id'].map(label_map)

    for cid, lbl in label_map.items():
        print(f"    Cluster {cid} → {lbl} ({(df['cluster_id'] == cid).sum()} players)")

    from sklearn.metrics import r2_score, mean_squared_error
    r2   = r2_score(df['market_value_in_eur'], df['predicted_value'])
    rmse = np.sqrt(mean_squared_error(df['market_value_in_eur'], df['predicted_value']))
    print(f"  Formula R²={r2:.4f}  RMSE={rmse:,.0f}")

    df.attrs.update({'best_model_name': 'Formula', 'best_r2': r2, 'best_rmse': rmse})
    return df

df = train_models(df, feature_cols, X_cluster_scaled)

