def load_data(data_dir):
    print('[STEP 1] Loading CSVs...')
    players     = pd.read_csv(os.path.join(data_dir, 'players.csv'))
    clubs       = pd.read_csv(os.path.join(data_dir, 'clubs.csv'))
    valuations  = pd.read_csv(os.path.join(data_dir, 'player_valuations.csv'))
    appearances = pd.read_csv(os.path.join(data_dir, 'appearances.csv'))

    print(f'  players: {len(players)} | clubs: {len(clubs)} | '
          f'valuations: {len(valuations)} | appearances: {len(appearances)}')

    # Aggregate appearances per player
    apps_agg = (appearances
                .groupby('player_id', as_index=False)
                .agg(total_goals=('goals', 'sum'),
                     total_assists=('assists', 'sum'),
                     total_minutes_played=('minutes_played', 'sum')))

    # Latest valuation per player (target variable)
    valuations['date'] = pd.to_datetime(valuations['date'], errors='coerce')
    latest_val = (valuations
                  .sort_values('date', ascending=False)
                  .drop_duplicates(subset='player_id', keep='first')
                  [['player_id', 'date', 'market_value_in_eur']]
                  .rename(columns={'date': 'valuation_date'}))

    # players.csv → current_club_id | clubs.csv → club_id
    df = players.merge(
        clubs,
        left_on='current_club_id',
        right_on='club_id',
        how='inner',
        suffixes=('_player', '_club')
    )
    print(f'  After players⨝clubs (inner): {len(df)} rows')

    df = df.merge(apps_agg,   on='player_id', how='left')
    df = df.merge(latest_val, on='player_id', how='left')

    # Birden fazla market_value kolonu varsa birleştir
    if 'market_value_in_eur_y' in df.columns:
        df['market_value_in_eur'] = df['market_value_in_eur_y'].fillna(df['market_value_in_eur_x'])
        df.drop(columns=['market_value_in_eur_x', 'market_value_in_eur_y'], inplace=True)
    elif 'market_value_in_eur_x' in df.columns:
        df.rename(columns={'market_value_in_eur_x': 'market_value_in_eur'}, inplace=True)

    df = df.dropna(subset=['market_value_in_eur']).reset_index(drop=True)
    print(f'  Final rows (with market value): {len(df)}')
    return df

